-- Enterprise Banking Oracle DDL Schema Script

-- 1. USERS & SECURITY TABLE
CREATE TABLE USERS (
    USER_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    PHONE_NUMBER VARCHAR2(20) NOT NULL,
    USER_ROLE VARCHAR2(20) DEFAULT 'CUSTOMER' NOT NULL,
    IS_ENABLED NUMBER(1,0) DEFAULT 1 NOT NULL,
    IS_LOCKED NUMBER(1,0) DEFAULT 0 NOT NULL,
    FAILED_ATTEMPTS NUMBER(3,0) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. CUSTOMERS TABLE
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER(19,0) NOT NULL UNIQUE,
    FIRST_NAME VARCHAR2(50) NOT NULL,
    LAST_NAME VARCHAR2(50) NOT NULL,
    DATE_OF_BIRTH DATE NOT NULL,
    TAX_IDENTIFICATION_NUMBER VARCHAR2(30) NOT NULL UNIQUE,
    NATIONAL_ID VARCHAR2(30) NOT NULL UNIQUE,
    KYC_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    ADDRESS_LINE1 VARCHAR2(100) NOT NULL,
    ADDRESS_LINE2 VARCHAR2(100),
    CITY VARCHAR2(50) NOT NULL,
    STATE VARCHAR2(50) NOT NULL,
    POSTAL_CODE VARCHAR2(20) NOT NULL,
    COUNTRY VARCHAR2(50) DEFAULT 'USA' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CUSTOMER_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- 3. ACCOUNTS TABLE
CREATE TABLE ACCOUNTS (
    ACCOUNT_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_NUMBER VARCHAR2(20) NOT NULL UNIQUE,
    CUSTOMER_ID NUMBER(19,0) NOT NULL,
    ACCOUNT_TYPE VARCHAR2(20) NOT NULL, -- SAVINGS, CHECKING, FIXED_DEPOSIT, LOAN
    CURRENCY VARCHAR2(3) DEFAULT 'USD' NOT NULL,
    BALANCE NUMBER(19,4) DEFAULT 0.0000 NOT NULL,
    AVAILABLE_BALANCE NUMBER(19,4) DEFAULT 0.0000 NOT NULL,
    ACCOUNT_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    OVERDRAFT_LIMIT NUMBER(19,4) DEFAULT 0.0000 NOT NULL,
    INTEREST_RATE NUMBER(5,4) DEFAULT 0.0000 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_ACCOUNT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID)
);

-- 4. TRANSACTIONS TABLE
CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRANSACTION_REFERENCE VARCHAR2(36) NOT NULL UNIQUE,
    SOURCE_ACCOUNT_ID NUMBER(19,0),
    DESTINATION_ACCOUNT_ID NUMBER(19,0),
    TRANSACTION_TYPE VARCHAR2(30) NOT NULL, -- DEPOSIT, WITHDRAWAL, TRANSFER, LOAN_DISBURSEMENT, EMI_PAYMENT, CARD_PAYMENT
    AMOUNT NUMBER(19,4) NOT NULL,
    FEE_AMOUNT NUMBER(19,4) DEFAULT 0.0000 NOT NULL,
    CURRENCY VARCHAR2(3) DEFAULT 'USD' NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL, -- PENDING, COMPLETED, FAILED, REVERSED
    DESCRIPTION VARCHAR2(255),
    FAILURE_REASON VARCHAR2(255),
    INITIATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    CONSTRAINT FK_TX_SOURCE_ACC FOREIGN KEY (SOURCE_ACCOUNT_ID) REFERENCES ACCOUNTS(ACCOUNT_ID),
    CONSTRAINT FK_TX_DEST_ACC FOREIGN KEY (DESTINATION_ACCOUNT_ID) REFERENCES ACCOUNTS(ACCOUNT_ID)
);

-- 5. LOANS TABLE
CREATE TABLE LOANS (
    LOAN_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOAN_NUMBER VARCHAR2(20) NOT NULL UNIQUE,
    CUSTOMER_ID NUMBER(19,0) NOT NULL,
    LOAN_TYPE VARCHAR2(30) NOT NULL, -- PERSONAL, HOME, AUTO, BUSINESS
    PRINCIPAL_AMOUNT NUMBER(19,4) NOT NULL,
    OUTSTANDING_PRINCIPAL NUMBER(19,4) NOT NULL,
    ANNUAL_INTEREST_RATE NUMBER(5,4) NOT NULL,
    TENURE_MONTHS NUMBER(5,0) NOT NULL,
    MONTHLY_EMI NUMBER(19,4) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'APPLIED' NOT NULL, -- APPLIED, APPROVED, DISBURSED, ACTIVE, CLOSED, DEFAULTED
    DISBURSEMENT_DATE DATE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_LOAN_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID)
);

-- 6. EMI REPAYMENT SCHEDULE TABLE
CREATE TABLE EMI_SCHEDULES (
    SCHEDULE_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOAN_ID NUMBER(19,0) NOT NULL,
    INSTALLMENT_NUMBER NUMBER(5,0) NOT NULL,
    DUE_DATE DATE NOT NULL,
    PRINCIPAL_COMPONENT NUMBER(19,4) NOT NULL,
    INTEREST_COMPONENT NUMBER(19,4) NOT NULL,
    TOTAL_EMI_AMOUNT NUMBER(19,4) NOT NULL,
    PAID_AMOUNT NUMBER(19,4) DEFAULT 0.0000 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'UNPAID' NOT NULL, -- UNPAID, PAID, PARTIAL, OVERDUE
    PAYMENT_DATE DATE,
    CONSTRAINT FK_EMI_LOAN FOREIGN KEY (LOAN_ID) REFERENCES LOANS(LOAN_ID)
);

-- 7. CARDS TABLE
CREATE TABLE CARDS (
    CARD_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CARD_NUMBER_MASKED VARCHAR2(19) NOT NULL,
    CARD_HASH VARCHAR2(100) NOT NULL UNIQUE,
    ACCOUNT_ID NUMBER(19,0) NOT NULL,
    CARD_TYPE VARCHAR2(20) NOT NULL, -- DEBIT, CREDIT
    EXPIRY_DATE DATE NOT NULL,
    CVV_HASH VARCHAR2(100) NOT NULL,
    CARD_STATUS VARCHAR2(20) DEFAULT 'INACTIVE' NOT NULL, -- ACTIVE, INACTIVE, BLOCKED, EXPIRED
    DAILY_ATM_LIMIT NUMBER(19,4) DEFAULT 1000.00 NOT NULL,
    DAILY_POS_LIMIT NUMBER(19,4) DEFAULT 5000.00 NOT NULL,
    CREDIT_LIMIT NUMBER(19,4) DEFAULT 0.0000,
    USED_CREDIT NUMBER(19,4) DEFAULT 0.0000,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CARD_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS(ACCOUNT_ID)
);

-- 8. AUDIT LOGS TABLE
CREATE TABLE AUDIT_LOGS (
    AUDIT_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTION VARCHAR2(100) NOT NULL,
    PERFORMED_BY VARCHAR2(50) NOT NULL,
    ENTITY_NAME VARCHAR2(50) NOT NULL,
    ENTITY_ID VARCHAR2(50),
    OLD_STATE CLOB,
    NEW_STATE CLOB,
    IP_ADDRESS VARCHAR2(45),
    TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 9. NOTIFICATIONS TABLE
CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER(19,0) NOT NULL,
    NOTIFICATION_TYPE VARCHAR2(30) NOT NULL, -- EMAIL, SMS, IN_APP
    SUBJECT VARCHAR2(150),
    MESSAGE VARCHAR2(1000) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL, -- PENDING, SENT, FAILED
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_NOTIF_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

-- INDEXES FOR PERFORMANCE OPTIMIZATION
CREATE INDEX IDX_ACC_CUST ON ACCOUNTS(CUSTOMER_ID);
CREATE INDEX IDX_TX_SOURCE ON TRANSACTIONS(SOURCE_ACCOUNT_ID);
CREATE INDEX IDX_TX_DEST ON TRANSACTIONS(DESTINATION_ACCOUNT_ID);
CREATE INDEX IDX_TX_REF ON TRANSACTIONS(TRANSACTION_REFERENCE);
CREATE INDEX IDX_LOAN_CUST ON LOANS(CUSTOMER_ID);
CREATE INDEX IDX_EMI_LOAN ON EMI_SCHEDULES(LOAN_ID);
CREATE INDEX IDX_CARD_ACC ON CARDS(ACCOUNT_ID);
CREATE INDEX IDX_AUDIT_TIMESTAMP ON AUDIT_LOGS(TIMESTAMP);
